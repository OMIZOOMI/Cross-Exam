import { describe, expect, it } from "vitest";
import { classifyAddress } from "./ip-policy";

describe("conservative destination address classification", () => {
  it.each([
    ["0.0.0.0", "unspecified"],
    ["0.255.255.255", "unspecified"],
    ["127.0.0.1", "loopback"],
    ["127.255.255.255", "loopback"],
    ["10.0.0.1", "private"],
    ["10.255.255.255", "private"],
    ["172.16.0.0", "private"],
    ["172.31.255.255", "private"],
    ["192.168.1.1", "private"],
    ["169.254.0.1", "link-local"],
    ["169.254.169.254", "link-local"],
    ["169.254.170.2", "link-local"],
    ["100.64.0.0", "shared"],
    ["100.127.255.255", "shared"],
    ["100.100.100.200", "shared"],
    ["224.0.0.0", "multicast"],
    ["239.255.255.255", "multicast"],
    ["240.0.0.0", "reserved"],
    ["255.255.255.255", "reserved"],
    ["192.0.0.9", "reserved"],
    ["192.31.196.1", "reserved"],
    ["192.52.193.1", "reserved"],
    ["192.175.48.1", "reserved"],
    ["192.88.99.2", "translation"],
    ["192.0.2.1", "documentation"],
    ["198.51.100.1", "documentation"],
    ["203.0.113.1", "documentation"],
    ["198.18.0.1", "benchmark"],
    ["198.19.255.255", "benchmark"],
    ["168.63.129.16", "cloud-platform"],
    ["::", "unspecified"],
    ["::1", "loopback"],
    ["fc00::1", "private"],
    ["fdff:ffff::1", "private"],
    ["fd00:ec2::254", "private"],
    ["fe80::1", "link-local"],
    ["febf:ffff::1", "link-local"],
    ["ff00::1", "multicast"],
    ["ffff::1", "multicast"],
    ["fec0::1", "reserved"],
    ["::ffff:127.0.0.1", "ipv4-mapped"],
    ["::FFFF:808:808", "ipv4-mapped"],
    ["::ffff:192.168.0.1", "ipv4-mapped"],
    ["64:ff9b::a00:1", "translation"],
    ["64:ff9b:1::1", "translation"],
    ["2001::1", "reserved"],
    ["2001:1::1", "reserved"],
    ["2001:20::1", "reserved"],
    ["2001:1ff:ffff::1", "reserved"],
    ["2001:db8::1", "documentation"],
    ["2002:7f00:1::1", "translation"],
    ["2620:4f:8000::1", "reserved"],
    ["3fff::1", "documentation"],
    ["3fff:fff:ffff::1", "documentation"],
    ["100::1", "reserved"],
    ["100:0:0:1::1", "reserved"],
    ["5f00::1", "reserved"],
    ["::127.0.0.1", "ipv4-mapped"],
  ])("blocks %s as %s", (address, classification) =>
    expect(classifyAddress(address)).toEqual({ ok: false, classification }),
  );
  it.each([
    "8.8.8.8",
    "1.1.1.1",
    "93.184.216.34",
    "172.15.255.255",
    "172.32.0.0",
    "100.63.255.255",
    "100.128.0.0",
    "192.167.255.255",
    "192.169.0.0",
    "198.17.255.255",
    "198.20.0.0",
    "223.255.255.255",
    "168.63.129.17",
    "2001:200::1",
    "2606:4700:4700::1111",
    "2001:4860:4860::8888",
    "3ffe:ffff::1",
    "3fff:1000::1",
  ])("permits ordinary public address %s", (address) =>
    expect(classifyAddress(address)).toMatchObject({ ok: true, classification: "public" }),
  );
  it.each([
    "127.1",
    "2130706433",
    "0x7f000001",
    "0177.0.0.1",
    "1.2.3.999",
    "not-ip",
    "example.com",
    "[::1]",
    "fe80::1%en0",
    "2606:4700::1111%en0",
    "8.8.8.8\n",
    "",
    "1::2::3",
  ])("rejects malformed resolver output %s", (address) =>
    expect(classifyAddress(address)).toEqual({ ok: false, classification: "invalid" }),
  );
});
